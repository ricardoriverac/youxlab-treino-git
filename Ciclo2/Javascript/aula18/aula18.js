// DIFERENÇA DE WHILE E DO WHILE

let numero=10

while(numero<10){ // false 
    console.log('Curso de Javascript')
    numero++
}
console.log('Fim do programa \n')// imprimirá está frase diretamente 


// DO WHILE
// FAÇA comandos ENQUANTO número menor que 10
// Faz com que o loop fosse interado pelo menos 1 vez
do{ 
    console.log('Curso de Javascript')
    numero++
}while(numero<10)
console.log('Fim do programa')